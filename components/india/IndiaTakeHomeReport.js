// Effective-rate lines across the salary range. Crosshair and tooltip follow
// the pointer; the table below is the full data view.
function RateChart() {
  const [hover, setHover] = useState(null);
  const W = 720; const Hh = 320;
  const m = { top: 20, right: 150, bottom: 36, left: 44 };
  const iw = W - m.left - m.right; const ih = Hh - m.top - m.bottom;
  const xs = ROWS.map((r) => r.lakh);
  const x0 = xs[0]; const x1 = xs[xs.length - 1];
  const yMax = Math.ceil(Math.max(...ROWS.map((r) => r.oldEffectiveRate)) / 5) * 5;
  const x = (l) => m.left + ((l - x0) / (x1 - x0)) * iw;
  const y = (v) => m.top + ih - (v / yMax) * ih;
  const path = (key) => ROWS.map((r, i) => `${i ? 'L' : 'M'}${x(r.lakh).toFixed(1)},${y(r[key]).toFixed(1)}`).join(' ');
  const yTicks = Array.from({ length: yMax / 5 + 1 }, (_, i) => i * 5);
  const xTicks = [5, 10, 15, 20, 25, 30, 35, 40, 45, 50];

  const onMove = (e) => {
    const rect = e.currentTarget.getBoundingClientRect();
    const px = ((e.clientX - rect.left) / rect.width) * W;
    const l = Math.round(x0 + ((px - m.left) / iw) * (x1 - x0));
    setHover(Math.min(x1, Math.max(x0, l)));
  };
  // End-of-line labels: push apart any that would overlap (min 13px gap).
  const last = ROWS[ROWS.length - 1];
  const labelY = (() => {
    const sorted = SERIES.map((s) => ({ key: s.key, y: y(last[s.key]) })).sort((a, b) => a.y - b.y);
    for (let i = 1; i < sorted.length; i += 1) sorted[i].y = Math.max(sorted[i].y, sorted[i - 1].y + 13);
    return Object.fromEntries(sorted.map((s) => [s.key, s.y]));
  })();
  const hr = hover ? ROWS.find((r) => r.lakh === hover) : null;
  const tipX = hr ? (x(hr.lakh) > W - m.right - 170 ? x(hr.lakh) - 178 : x(hr.lakh) + 10) : 0;

  return (
    <Card className="p-4 sm:p-5">
      <p className="font-semibold text-ink dark:text-white">Effective income tax rate by salary, FY 2026-27</p>
      <p className="mt-0.5 text-xs text-ink-muted dark:text-slate-400">Tax plus cess as a share of gross salary. Hover or tap for the figures at any salary.</p>
      <div className="relative mt-3 w-full overflow-hidden">
        <svg viewBox={`0 0 ${W} ${Hh}`} className="h-auto w-full touch-none" role="img" aria-label="Line chart of effective tax rate from 5 to 50 lakh under the new regime and the old regime with and without deductions" onMouseMove={onMove} onMouseLeave={() => setHover(null)} onTouchStart={(e) => onMove(e.touches[0] ? { currentTarget: e.currentTarget, clientX: e.touches[0].clientX } : e)} onTouchMove={(e) => onMove(e.touches[0] ? { currentTarget: e.currentTarget, clientX: e.touches[0].clientX } : e)}>
          {yTicks.map((t) => (
            <g key={t}>
              <line x1={m.left} x2={W - m.right} y1={y(t)} y2={y(t)} className="stroke-slate-200 dark:stroke-slate-700" strokeWidth="1" />
              <text x={m.left - 8} y={y(t) + 4} textAnchor="end" className="fill-ink-muted text-[11px] dark:fill-slate-400">{t}%</text>
            </g>
          ))}
          {xTicks.map((t) => (
            <text key={t} x={x(t)} y={Hh - m.bottom + 18} textAnchor="middle" className="fill-ink-muted text-[11px] dark:fill-slate-400">₹{t}L</text>
          ))}
          <line x1={m.left} x2={W - m.right} y1={y(0)} y2={y(0)} className="stroke-slate-300 dark:stroke-slate-600" strokeWidth="1" />
          {SERIES.map((s) => (
            <g key={s.key}>
              <path d={path(s.key)} fill="none" strokeWidth="2" strokeLinejoin="round" strokeLinecap="round" style={{ stroke: `var(--s-${s.key})` }} />
              <text x={W - m.right + 8} y={labelY[s.key] + 4} className="fill-ink text-[11px] font-medium dark:fill-slate-200">{s.label.split(',')[0]}{s.key === 'oldEffectiveRate' ? ' (no ded.)' : s.key === 'oldTypicalEffectiveRate' ? ' (typical ded.)' : ''}</text>
            </g>
          ))}
          {hr && (
            <g>
              <line x1={x(hr.lakh)} x2={x(hr.lakh)} y1={m.top} y2={y(0)} className="stroke-slate-400 dark:stroke-slate-500" strokeDasharray="3 3" />
              {SERIES.map((s) => <circle key={s.key} cx={x(hr.lakh)} cy={y(hr[s.key])} r="4.5" className="stroke-white dark:stroke-slate-800" strokeWidth="2" style={{ fill: `var(--s-${s.key})` }} />)}
              <g transform={`translate(${tipX}, ${m.top})`}>
                <rect width="168" height="78" rx="8" className="fill-white stroke-slate-200 dark:fill-slate-800 dark:stroke-slate-600" />
                <text x="10" y="18" className="fill-ink text-[12px] font-semibold dark:fill-white">₹{hr.lakh} lakh salary</text>
                <text x="10" y="36" className="fill-ink-soft text-[11px] dark:fill-slate-300">New: {pct(hr.newEffectiveRate)} · {inr(hr.newTax)}</text>
                <text x="10" y="52" className="fill-ink-soft text-[11px] dark:fill-slate-300">Old, typical ded.: {pct(hr.oldTypicalEffectiveRate)}</text>
                <text x="10" y="68" className="fill-ink-soft text-[11px] dark:fill-slate-300">Old, no ded.: {pct(hr.oldEffectiveRate)}</text>
              </g>
            </g>
          )}
        </svg>
      </div>
      <ul className="mt-3 flex flex-wrap gap-x-5 gap-y-1.5 text-xs text-ink-soft dark:text-slate-300">
        {SERIES.map((s) => (
          <li key={s.key} className="inline-flex items-center gap-2"><span className="inline-block h-0.5 w-5 rounded" style={{ background: `var(--s-${s.key})` }} />{s.label}</li>
        ))}
      </ul>
      <style jsx>{`
        :global(:root) { --s-newEffectiveRate: ${SERIES[0].light}; --s-oldTypicalEffectiveRate: ${SERIES[1].light}; --s-oldEffectiveRate: ${SERIES[2].light}; }
        :global(body.dark-theme) { --s-newEffectiveRate: ${SERIES[0].dark}; --s-oldTypicalEffectiveRate: ${SERIES[1].dark}; --s-oldEffectiveRate: ${SERIES[2].dark}; }
      `}</style>
    </Card>
  );
}

function CiteBox() {
  const [copied, setCopied] = useState('');
  const text = `Upaman, "India Take-Home Salary Report FY 2026-27", ${URL} (accessed ${new Date().getFullYear()})`;
  const html = `<a href="${URL}">India Take-Home Salary Report FY 2026-27 — Upaman</a>`;
  const copy = async (what, value) => {
    try { await navigator.clipboard.writeText(value); setCopied(what); window.setTimeout(() => setCopied(''), 2000); } catch (e) { /* ignore */ }
  };
  return (
    <Card className="p-5">
      <p className="font-semibold text-ink dark:text-white">Cite or link to this report</p>
      <p className="mt-1 text-sm text-ink-muted dark:text-slate-400">Free to quote and republish with attribution. The dataset is updated when a Budget changes the slabs, at this same URL.</p>
      <div className="mt-3 grid gap-2 sm:grid-cols-2">
        <button type="button" onClick={() => copy('cite', text)} className="inline-flex items-center justify-center gap-2 rounded-xl border border-slate-200 px-4 py-2 text-sm font-medium text-ink-soft transition hover:border-brand-300 hover:text-brand-700 dark:border-slate-700 dark:text-slate-300">
          {copied === 'cite' ? <Check className="h-4 w-4 text-emerald-500" /> : <Link2 className="h-4 w-4" />}{copied === 'cite' ? 'Copied' : 'Copy citation'}
        </button>
        <button type="button" onClick={() => copy('html', html)} className="inline-flex items-center justify-center gap-2 rounded-xl border border-slate-200 px-4 py-2 text-sm font-medium text-ink-soft transition hover:border-brand-300 hover:text-brand-700 dark:border-slate-700 dark:text-slate-300">
          {copied === 'html' ? <Check className="h-4 w-4 text-emerald-500" /> : <Link2 className="h-4 w-4" />}{copied === 'html' ? 'Copied' : 'Copy HTML link'}
        </button>
      </div>
    </Card>
  );
}

